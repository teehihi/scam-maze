const { prune, dedup, weld, resample, quantize, reorder, meshopt, simplify } = require("@gltf-transform/functions");
const { MeshoptEncoder, MeshoptDecoder, MeshoptSimplifier } = require("meshoptimizer");
const sharp = require("sharp");
